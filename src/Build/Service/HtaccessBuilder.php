<?php

declare(strict_types=1);

namespace Fastsite\Build\Service;

use Fastsite\Site\Dto\Site;
use Fastsite\Site\Service\RedirectService;

/**
 * The Apache translation of everything `_headers` and `_redirects` promise.
 *
 * Those two files are a Cloudflare Pages convention — inert text on a customer's
 * own shared host. Without this an FTP-published site silently loses its CSP,
 * its immutable caching and its www↔apex 301, which is both a security
 * regression and a measurable PageSpeed loss on the caching audit. Apache and
 * LiteSpeed (which reads .htaccess too) cover the overwhelming majority of
 * shared hosting, so this closes the gap for nearly every customer.
 *
 * Pure and DB-free, like JsonLdBuilder: the caller passes the redirect rows in,
 * so the whole file is unit-testable without a container.
 *
 * Two things it can do that `_redirects` structurally cannot: a real host-level
 * 301 (a CDN needs a zone rule for that) and a real 410 (`_redirects` expresses
 * 3xx only and has to ship Gone as a comment).
 */
final class HtaccessBuilder
{
    /**
     * @param list<array{from_path: string, to_path: string, status: int}> $redirects
     * @param string $csp the exact Content-Security-Policy `_headers` carries,
     *                    passed in so the two can never disagree
     * @param list<int> $errorPages statuses this build emitted a `/{code}.html`
     *                              for. 404 is always wired up, with or without
     *                              a row, because the build always emits one.
     */
    public function build(Site $site, array $redirects, string $csp, array $errorPages = []): string
    {
        $out = "# Generated by fastsite on every publish — do not edit by hand.\n";
        $out .= "# Anything you change here is overwritten the next time the site is published.\n\n";

        $out .= "Options -Indexes\n";
        $out .= "DirectoryIndex index.html\n";

        // Without this the customer's HOST serves its own 404 page instead of
        // the one the build produced.
        //
        // Apache is the one serving mode that can honour EVERY configured
        // status — Cloudflare Pages has a convention for 404 and nothing else,
        // and DirectServeGate only ever produces 404 and 410. So this is where
        // a custom 403 or 410 actually earns its keep.
        //
        // 410 in particular: `redirectBlock` below emits a real
        // `RedirectMatch 410` per Gone rule, but without a matching
        // ErrorDocument Apache answers it with ITS OWN body — so the customer
        // got a correct status wrapped in a stranger's error page.
        $codes = array_values(array_unique([404, ...$errorPages]));
        sort($codes);
        foreach ($codes as $code) {
            $out .= sprintf("ErrorDocument %d /%d.html\n", $code, $code);
        }
        $out .= "\n";

        $out .= $this->canonicalBlock($site);
        $out .= $this->redirectBlock($redirects);
        $out .= $this->headerBlock($csp, $site->development);

        return $out;
    }

    /**
     * One rule for the canonical host AND https, because they are the same
     * question: "is this the single origin the build's canonical tags, sitemap
     * and OG tags all name?" Splitting them into two rules costs a second
     * redirect hop on the common wrong-host-and-http case.
     *
     * The https half is not optional: every absolute URL in the build already
     * says https, so a site served over plain http is shipping contradictory
     * signals to Google either way. Redirecting is the honest failure — it
     * breaks loudly on a host without a certificate instead of quietly ranking
     * badly.
     */
    private function canonicalBlock(Site $site): string
    {
        $canonical = $site->canonicalBaseUrl();
        if ($canonical === '') {
            return '';
        }
        $host = parse_url($canonical, PHP_URL_HOST);
        if (!\is_string($host) || $host === '') {
            return '';
        }

        return "<IfModule mod_rewrite.c>\n"
            . "  RewriteEngine On\n"
            . "  # Wrong host, or not https (checked behind a proxy too) → one 301\n"
            . "  # to the single origin every canonical tag in this build names.\n"
            . '  RewriteCond %{HTTP_HOST} !^' . $this->rewriteQuote($host) . "$ [NC,OR]\n"
            . "  RewriteCond %{HTTPS} !=on\n"
            . "  RewriteCond %{HTTP:X-Forwarded-Proto} !=https\n"
            . '  RewriteRule ^ ' . rtrim($canonical, '/') . "%{REQUEST_URI} [L,R=301]\n"
            . "</IfModule>\n\n";
    }

    /**
     * @param list<array{from_path: string, to_path: string, status: int}> $redirects
     */
    private function redirectBlock(array $redirects): string
    {
        if ($redirects === []) {
            return '';
        }

        $lines = '';
        foreach ($redirects as $row) {
            $from = (string) $row['from_path'];
            if ($from === '' || $from[0] !== '/') {
                continue;
            }
            $status = (int) $row['status'];
            // RedirectMatch, not Redirect: mod_alias's Redirect matches by
            // PREFIX, so a rule for /a would also fire on /about. Anchored and
            // escaped, with an optional trailing slash so both forms resolve.
            $pattern = '^' . $this->regexQuote($from) . '/?$';

            if ($status === RedirectService::GONE) {
                // A real 410 — the thing `_redirects` cannot express at all.
                $lines .= sprintf("RedirectMatch 410 %s\n", $pattern);
                continue;
            }

            $to = (string) $row['to_path'];
            if ($to === '') {
                continue;
            }
            $lines .= sprintf("RedirectMatch %d %s %s\n", $status, $pattern, $to);
        }

        if ($lines === '') {
            return '';
        }

        return "# Redirects (fastsite `redirects` table)\n" . $lines . "\n";
    }

    private function headerBlock(string $csp, bool $development = false): string
    {
        // ONE CSP for the whole site here, where `_headers` now carries a
        // per-page policy. The `$csp` handed in is therefore the WIDEST any
        // page needs, so an ftp site is over-permissive on pages that ship no
        // script rather than under-permissive on the one that does.
        //
        // Per-path is expressible — `SetEnvIf Request_URI` + a second
        // `Header always set ... env=` would do it, exactly as the caching
        // rule below works. It is deliberately not done, because its failure
        // mode is the wrong way round: a host without mod_setenvif would never
        // set the env, the strict policy would apply everywhere, and the
        // customer's scripted page would have its script BLOCKED — silently,
        // visible only in a console nobody opens. Over-permissive degrades a
        // policy; under-permissive breaks a live site, and this file runs on
        // hosts we cannot test. Revisit with a real Apache to try it against.
        //
        // Scoped by PATH rather than by extension, so this stays a faithful
        // translation of _headers' /assets/* /media/* /files/* rules — those
        // directories are immutable because their filenames carry a content
        // hash or a media id, which is not a property of the extension.
        return "<IfModule mod_setenvif.c>\n"
            . "  SetEnvIf Request_URI \"^/(assets|media|files)/\" FS_IMMUTABLE=1\n"
            . "</IfModule>\n\n"
            . "<IfModule mod_headers.c>\n"
            . "  Header always set X-Content-Type-Options \"nosniff\"\n"
            . "  Header always set Referrer-Policy \"strict-origin-when-cross-origin\"\n"
            . '  Header always set Content-Security-Policy "' . $this->headerQuote($csp) . "\"\n"
            // Development mode's header half. The meta tag lives inside HTML
            // only, so a PDF or an image published to the customer's host is
            // otherwise still indexable — and this file is the ONLY thing that
            // sets headers there, since Apache reads neither `_headers` nor
            // anything else fastsite emits.
            . ($development ? "  Header always set X-Robots-Tag \"noindex, nofollow\"\n" : '')
            . "  Header set Cache-Control \"public, max-age=31536000, immutable\" env=FS_IMMUTABLE\n"
            . "</IfModule>\n";
    }

    /** Escape for a RewriteCond regex, and keep it on one line. */
    private function rewriteQuote(string $value): string
    {
        return preg_quote($this->oneLine($value), '#');
    }

    /** Escape for a RedirectMatch regex. */
    private function regexQuote(string $value): string
    {
        return preg_quote($this->oneLine($value), '#');
    }

    /**
     * A header value lands inside a double-quoted Apache directive, so a quote
     * or a newline in it would end the directive early and turn the rest into
     * arbitrary configuration on the customer's server.
     */
    private function headerQuote(string $value): string
    {
        return str_replace(['"', '\\'], ['', ''], $this->oneLine($value));
    }

    /**
     * .htaccess is line-oriented: an embedded newline anywhere would let a
     * stored value inject its own directive.
     */
    private function oneLine(string $value): string
    {
        return trim((string) preg_replace('/\s+/', ' ', $value));
    }
}
