<?php

declare(strict_types=1);

namespace Fastsite\Tests\Integration;

use Fastsite\Build\Service\BuildService;
use Fastsite\Content\Repository\DbalContentRepository;
use Fastsite\Content\Service\ContentSanitizer;
use Fastsite\Content\Service\ContentService;
use Fastsite\Shared\Clock\SystemClock;
use Fastsite\Shared\Database\Migrator;
use Fastsite\Shared\Database\SiteDatabaseManager;
use Fastsite\Site\Repository\DbalSiteRepository;
use Fastsite\Site\Service\SiteService;
use PHPUnit\Framework\TestCase;
use Psr\Log\NullLogger;

/**
 * End-to-end M1 flow against a throwaway data dir: provision site,
 * create content, build, assert static output + incremental skip.
 */
final class WalkingSkeletonTest extends TestCase
{
    private string $dataPath;
    private string $appRoot;
    private SiteDatabaseManager $databases;
    private SiteService $sites;
    private ContentService $content;
    private BuildService $build;

    protected function setUp(): void
    {
        $this->appRoot = \dirname(__DIR__, 2);
        $this->dataPath = sys_get_temp_dir() . '/fastsite-test-' . bin2hex(random_bytes(6));

        $clock = new SystemClock();
        $this->databases = new SiteDatabaseManager($this->dataPath);
        $migrator = new Migrator($clock);
        $siteRepo = new DbalSiteRepository($this->databases, $clock);
        $contentRepo = new DbalContentRepository($this->databases, $clock);
        $mediaRepo = new \Fastsite\Media\Repository\DbalMediaRepository($this->databases, $clock);

        $migrator->migrate($this->databases->engine(), $this->appRoot . '/migrations/engine');

        $this->sites = new SiteService($siteRepo, $this->databases, $migrator, $clock, new NullLogger(), $this->appRoot);
        $this->content = new ContentService($contentRepo, new ContentSanitizer(), $clock);
        $translationRepo = new \Fastsite\Translation\Repository\DbalTranslationRepository($this->databases, $clock);
        $componentRenderer = new \Fastsite\Build\Service\ComponentRenderer(new \Fastsite\Component\Repository\DbalComponentRepository($this->databases, $clock), $this->databases, new NullLogger(), $this->appRoot);
        $this->build = new BuildService($contentRepo, $this->databases, $clock, new NullLogger(), new \Fastsite\Build\Service\MediaRenderer($mediaRepo), $translationRepo, $componentRenderer, new \Fastsite\Build\Figlet\FigletRenderer(), new \Fastsite\Build\Service\FileRenderer($mediaRepo, $this->databases, new NullLogger(), $this->appRoot), $mediaRepo, new \Fastsite\Site\Service\SiteScriptService($this->databases, $clock));
    }

    protected function tearDown(): void
    {
        $this->databases->closeAll();

        if (!is_dir($this->dataPath)) {
            return;
        }
        $iterator = new \RecursiveIteratorIterator(
            new \RecursiveDirectoryIterator($this->dataPath, \FilesystemIterator::SKIP_DOTS),
            \RecursiveIteratorIterator::CHILD_FIRST,
        );
        foreach ($iterator as $item) {
            \assert($item instanceof \SplFileInfo);
            $item->isDir() ? rmdir($item->getPathname()) : unlink($item->getPathname());
        }
        rmdir($this->dataPath);
    }

    /**
     * The home page, blog index and 404 are generated by the engine, not from a
     * content row, so they had no description to emit and shipped without the
     * tag at all — which Lighthouse reports as an SEO failure on the site's most
     * important page. They now fall back to the site-level default, as does any
     * post or page authored with neither a seo_description nor an excerpt.
     */
    public function testSiteMetaDescriptionFillsEngineGeneratedPages(): void
    {
        $site = $this->sites->create('metatest', 'Meta Test', 'https://meta.example.com');
        $site = $this->sites->update($site->handle, [
            'meta_description' => 'Publishing engine for people who dislike page builders.',
        ]);

        $this->content->create($site, [
            'type' => 'post',
            'title' => 'Bare post',
            'body_html' => '<p>Body.</p>',
            'status' => 'published',
        ]);

        $this->build->build($site);

        $buildDir = $this->dataPath . '/sites/metatest/build';
        $expected = '<meta name="description" content="Publishing engine for people who dislike page builders.">';

        foreach (['/index.html', '/blog/index.html', '/404.html', '/blog/bare-post/index.html'] as $page) {
            self::assertStringContainsString(
                $expected,
                (string) file_get_contents($buildDir . $page),
                $page . ' shipped without a meta description',
            );
        }
    }

    public function testFullFlow(): void
    {
        $site = $this->sites->create('testsite', 'Test Site', 'https://test.example.com');

        self::assertFileExists($this->dataPath . '/sites/testsite/site.db');
        self::assertFileExists($this->dataPath . '/sites/testsite/shell/templates/base.html.twig');
        self::assertFileExists($this->dataPath . '/sites/testsite/shell/assets/tokens.css');

        $post = $this->content->create($site, [
            'type' => 'post',
            'title' => 'Første indlæg på Blå Bær',
            'excerpt' => 'A Danish title gets a clean ASCII slug.',
            'body_html' => '<p>Body.</p><script>alert(1)</script>',
            'status' => 'published',
        ]);

        self::assertSame('foerste-indlaeg-paa-blaa-baer', $post->slug);
        self::assertStringNotContainsString('script', $post->bodyHtml);
        self::assertNotSame([], $post->warnings);
        self::assertNotSame('', $post->contentHash);

        $stats = $this->build->build($site);

        $buildDir = $this->dataPath . '/sites/testsite/build';
        self::assertFileExists($buildDir . '/index.html');
        self::assertFileExists($buildDir . '/blog/index.html');
        self::assertFileExists($buildDir . '/blog/' . $post->slug . '/index.html');
        self::assertFileExists($buildDir . '/sitemap.xml');
        self::assertFileExists($buildDir . '/robots.txt');
        self::assertFileExists($buildDir . '/_headers');
        self::assertFileExists($buildDir . '/404.html');

        $html = (string) file_get_contents($buildDir . '/blog/' . $post->slug . '/index.html');
        self::assertStringContainsString('<link rel="canonical" href="https://test.example.com/blog/' . $post->slug . '/">', $html);
        self::assertStringContainsString('application/ld+json', $html);
        self::assertStringContainsString('<style>', $html);
        self::assertStringNotContainsString('<script>alert', $html);
        self::assertStringNotContainsString('src=', $html); // zero external resources

        // Second build: everything unchanged.
        $rebuild = $this->build->build($site);
        self::assertSame(0, $rebuild->written);
        self::assertSame($stats->pages, $rebuild->skipped);

        // Slug change writes a redirect and the old page disappears.
        $updated = $this->content->update($site, $post->id, ['slug' => 'renamed-post']);
        self::assertSame('renamed-post', $updated->slug);

        $third = $this->build->build($site);
        self::assertGreaterThan(0, $third->deleted);
        self::assertFileDoesNotExist($buildDir . '/blog/' . $post->slug . '/index.html');
        self::assertFileExists($buildDir . '/blog/renamed-post/index.html');
        self::assertStringContainsString(
            '/blog/foerste-indlaeg-paa-blaa-baer/ /blog/renamed-post/ 301',
            (string) file_get_contents($buildDir . '/_redirects'),
        );
        // Orphan cleanup must not leave empty per-slug directories behind.
        self::assertDirectoryDoesNotExist($buildDir . '/blog/' . $post->slug);
    }

    public function testSlugRenameBackLeavesNoRedirectLoop(): void
    {
        $site = $this->sites->create('looptest', 'Loop Test', 'https://loop.example.com');

        $post = $this->content->create($site, [
            'type' => 'post', 'title' => 'Original', 'body_html' => '<p>x</p>', 'status' => 'published',
        ]);

        // A → B → A: the final state must not redirect away from the live page.
        $this->content->update($site, $post->id, ['slug' => 'other']);
        $this->content->update($site, $post->id, ['slug' => 'original']);

        $this->build->build($site);

        $redirects = (string) file_get_contents($this->dataPath . '/sites/looptest/build/_redirects');
        self::assertStringContainsString('/blog/other/ /blog/original/ 301', $redirects);
        self::assertStringNotContainsString('/blog/original/ /blog/', $redirects);
    }

    public function testScriptBreakoutInTitleCannotEscapeJsonLd(): void
    {
        $site = $this->sites->create('xsstest', 'XSS Test', 'https://xss.example.com');

        $this->content->create($site, [
            'type' => 'post',
            'title' => 'How to use </script><script>alert(1)</script> safely',
            'excerpt' => 'Also here: </script>',
            'body_html' => '<p>x</p>',
            'status' => 'published',
            'author_name' => '</script>Eve',
        ]);

        $this->build->build($site);

        $files = glob($this->dataPath . '/sites/xsstest/build/blog/*/index.html') ?: [];
        self::assertCount(1, $files);
        $html = (string) file_get_contents($files[0]);

        // The raw-text <script> element must never see a literal "</script>"
        // from content — JSON_HEX_TAG turns every < and > into </>.
        self::assertStringNotContainsString('</script><script>alert', $html);
        preg_match('#<script type="application/ld\+json">(.*?)</script>#s', $html, $m);
        self::assertArrayHasKey(1, $m);
        self::assertStringNotContainsString('<', $m[1]);
        $decoded = json_decode(html_entity_decode($m[1]), true);
        self::assertIsArray($decoded);
        self::assertStringContainsString('alert(1)', (string) $decoded['headline']);
    }

    public function testReservedPageSlugCannotShadowEngineOutput(): void
    {
        $site = $this->sites->create('reserved', 'Reserved Test', 'https://r.example.com');

        $page = $this->content->create($site, [
            'type' => 'page', 'title' => 'Blog', 'slug' => 'blog', 'body_html' => '<p>x</p>', 'status' => 'published',
        ]);
        self::assertSame('blog-2', $page->slug);

        $this->build->build($site);

        $blogIndex = (string) file_get_contents($this->dataPath . '/sites/reserved/build/blog/index.html');
        self::assertStringNotContainsString('<p>x</p>', $blogIndex);
    }

    public function testSiteUpdateEditsAllFieldsAndNormalizesApex(): void
    {
        $site = $this->sites->create('editme', 'Before', 'https://before.example.com');
        self::assertSame('', $site->githubRepo, 'repo starts unset');

        $updated = $this->sites->update('editme', [
            'name' => 'After Co',
            'base_url' => 'https://www.after.example.com/', // www + slash
            'github_repo' => 'git@github.com:me/after-dist.git',
            'github_branch' => 'release',
            'media_public_base' => 'https://media.after.example.com/',
            'status' => 'paused',
        ]);

        self::assertSame('After Co', $updated->name);
        self::assertSame('https://after.example.com', $updated->baseUrl, 'www stripped to apex');
        self::assertSame('after.example.com', $updated->primaryDomain);
        self::assertSame('git@github.com:me/after-dist.git', $updated->githubRepo);
        self::assertSame('release', $updated->githubBranch);
        self::assertSame('https://media.after.example.com', $updated->mediaPublicBase);
        self::assertSame('paused', $updated->status);
        // Handle is immutable identity.
        self::assertSame('editme', $updated->handle);

        // A name/base-URL change must trigger a republish (canonicals change).
        self::assertTrue(\Fastsite\Site\Service\SiteService::changeNeedsRebuild($site, $updated));

        // Partial update leaves other fields alone.
        $again = $this->sites->update('editme', ['status' => 'active']);
        self::assertSame('active', $again->status);
        self::assertSame('After Co', $again->name);
        self::assertSame('git@github.com:me/after-dist.git', $again->githubRepo);
    }

    public function testSiteUpdateRejectsBadInput(): void
    {
        $this->sites->create('validate', 'V', 'https://v.example.com');

        foreach ([
            ['github_repo' => 'not a repo url'],
            ['github_branch' => 'bad branch!'],
            ['status' => 'bogus'],
            ['name' => '   '],
            ['media_public_base' => 'http://insecure.example.com'],
        ] as $bad) {
            try {
                $this->sites->update('validate', $bad);
                self::fail('Expected rejection for ' . json_encode($bad));
            } catch (\InvalidArgumentException) {
                self::assertTrue(true);
            }
        }

        // Clearing the repo (back to empty) is allowed.
        self::assertSame('', $this->sites->update('validate', ['github_repo' => ''])->githubRepo);
    }

    public function testGeneratedSeoFilesLlmsRobotsBannerAndApexCanonical(): void
    {
        // A non-ASCII name (the robots banner must stay printable-ASCII) and a
        // www base URL (must normalize to the apex).
        $site = $this->sites->create('seosite', 'Søren ApS', 'https://www.seo.example.com');
        self::assertSame('https://seo.example.com', $site->baseUrl);

        $this->content->create($site, [
            'type' => 'post', 'title' => 'Hello World', 'excerpt' => 'first post', 'body_html' => '<p>hi</p>', 'status' => 'published',
        ]);
        $this->build->build($site);
        $buildDir = $this->dataPath . '/sites/seosite/build';

        // llms.txt (llmstxt.org shape) with an apex-absolute link.
        $llms = (string) file_get_contents($buildDir . '/llms.txt');
        self::assertStringStartsWith('# ', $llms);
        self::assertStringContainsString('## Posts', $llms);
        self::assertStringContainsString('[Hello World](https://seo.example.com/blog/hello-world/)', $llms);

        // robots.txt: banner comment block + directives; every byte printable
        // ASCII even though the site name has non-ASCII characters.
        $robots = (string) file_get_contents($buildDir . '/robots.txt');
        self::assertStringStartsWith('####', $robots);
        self::assertStringContainsString('User-agent: *', $robots);
        self::assertStringContainsString('Sitemap: https://seo.example.com/sitemap.xml', $robots);
        self::assertStringContainsString('/llms.txt', $robots);
        self::assertMatchesRegularExpression('/^[\x20-\x7E\n]*$/', $robots, 'robots.txt must be printable ASCII');
        foreach (explode("\n", $robots) as $line) {
            self::assertLessThanOrEqual(78, \strlen($line));
        }

        // No dead www->apex line in _redirects (CF Pages can't express it);
        // the apex canonical is the working dedup mechanism.
        $redirectsFile = $buildDir . '/_redirects';
        if (is_file($redirectsFile)) {
            self::assertStringNotContainsString(':splat 301!', (string) file_get_contents($redirectsFile));
        }
        $post = (string) file_get_contents($buildDir . '/blog/hello-world/index.html');
        self::assertStringContainsString('<link rel="canonical" href="https://seo.example.com/blog/hello-world/">', $post);
    }
}
